function [names, aliases] = netgraph_option_names()

% [names, aliases] = netgraph_option_names()
%
% Names of all graphics options (fields of 'options' and of network.graphics_par)
% used by the functions in the folder 'graphics'
%
% names    cell array of option names
% aliases  (n x 2 cell array) other names that are accepted, and the option names they stand for
%
% Options are documented in 'help netgraph_draw' and in the help texts of the other functions.

persistent stored_names stored_aliases

if isempty(stored_names)

  % options of netgraph_draw
  draw = {'metvalues','metvalues_std','metvaluesmax','metvaluesmin','metstyle','metcolstyle','metcol', ...
          'metcolors','metinvisible','metprintnames','metprintvalues','omitmetabolites','show_metvalues', ...
          'actvalues','actvalues_std','actvaluesmax','actvaluesmin','actstyle','actcolstyle','actcol', ...
          'actcolors','actinvisible','actprintnames','actprintvalues','omitreactions','show_actvalues', ...
          'arrowstyle','arrowvalues','arrowvalues_std','arrowvaluesmax','arrowvaluesmin','arrow_stoichiometries', ...
          'arrowsize','arrow_shift','arrowprintvalues','straightlines','arrowcolor','flag_triangle_edges', ...
          'single_arrow','show_arrowvalues', ...
          'edgevalues','edgevalues_std','edgestyle','edgevaluesmax','edgevaluesmin','edgeprintvalues', ...
          'show_edgevalues','suppress_lines', ...
          'show_regulation','show_regulationvalues','regulationvalues','regulationvalues_std','regulationstyle', ...
          'regulationvaluesmax','regulationvaluesmin','regulationprintvalues','rlinecolor', ...
          'squaresize','no_points','flag_edges','circle_shift', ...
          'chop_names','split_names','FontSize','fontangle','text_offset','value_text_offset', ...
          'colorbar','colorbar_numbers','colorbar_fontsize','colorbar_location','linecolor','linewidth', ...
          'colormap','black_and_white','showsign','omit_zeros','shade_long_lines','shade_cofactor_lines', ...
          'canvas_position','canvas','figure_axis','figure_position','subplot_position','YDir','hold_on', ...
          'keep_subplot','scale_sizes'};

  % fields of network.graphics_par that are not display options
  graphics_par = {'x','fixed','m','db','N','metnames','actnames','metabolites','metabolite_mapping', ...
                  'reaction_mapping','regulation_matrix','lambda', ...
                  'x_split','N_split','m_split','db_split','fixed_split','split_back_mapping','display_split'};

  % fields computed by netgraph_draw (contained in the graphics_par it returns)
  computed = {'norm_metvalues','norm_metvalues_std','norm_actvalues','norm_actvalues_std','norm_arrowvalues', ...
              'norm_edgevalues','norm_edgevalues_std','norm_regulationvalues','norm_regulationvalues_std', ...
              'metindshow','actindshow','layout_size'};

  % options of other functions
  others = {'scale_arrowvalues', ...                                              % netgraph_concentrations
            'n_frames','timebar','timebar_labels','background_colors','use_background_colors', ...
            'flux_moves','metabolite_colors','reaction_colors','rest_frames','prefix', ...
            'colormap_1','colormap_2','set_circle_shift', ...                     % movies
            'manual','initial_relax','n_relaxation','frame', ...                  % netgraph_move
            'hide_invisible', ...                                                 % netgraph_edit_positions
            'show_diagonal_values','normalise_values','relative_threshold', ...   % synergy plots
            'verbose'};                                                           % netgraph_flux_in_large_network

  stored_names   = unique([draw, graphics_par, computed, others]);
  stored_aliases = {'Rotation', 'fontangle'};
end

names   = stored_names;
aliases = stored_aliases;
